package models

import (
	"errors"
	"time"
)

// AdminUser owns lists created by local tools and lists generated from
// external sources such as NSE indices.
const AdminUser = "ADMIN"

// ErrAlreadyExists indicates that a list with the same name already exists
// for the same user.
var ErrAlreadyExists = errors.New("lists: already exists")

// List is a named, user-owned set of instruments.
type List struct {
	ID            string
	CreatedBy     string
	Number        int
	Name          string
	IsIndex       bool
	AutoGenerated bool
	URL           string
	Items         []ListItem
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

// ListItem is one instrument in a list.
type ListItem struct {
	InstrumentID InstrumentID
	CreatedAt    time.Time
}

// InstrumentIDs returns the list's instrument IDs in list order.
func (l List) InstrumentIDs() []InstrumentID {
	ids := make([]InstrumentID, 0, len(l.Items))
	for _, item := range l.Items {
		ids = append(ids, item.InstrumentID)
	}
	return ids
}
