func TestListsCreateGetAndEditItems(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	created, err := store.CreateList(ctx, models.List{
		CreatedBy: models.AdminUser,
		Name:      " Banks ",
		Items:     []models.ListItem{{InstrumentID: "NSE:HDFCBANK"}, {InstrumentID: "NSE:ICICIBANK"}},
	})
	if err != nil {
		t.Fatalf("CreateList() error = %v", err)
	}
	if created.ID == "" || created.Number != 1 || created.Name != "Banks" || created.CreatedAt.IsZero() {
		t.Fatalf("created list = %#v", created)
	}
	assertListIDs(t, created, "NSE:HDFCBANK", "NSE:ICICIBANK")

	if _, err := store.CreateList(ctx, models.List{CreatedBy: models.AdminUser, Name: "Banks"}); !errors.Is(err, models.ErrAlreadyExists) {
		t.Fatalf("duplicate CreateList() error = %v, want ErrAlreadyExists", err)
	}
	if _, err := store.CreateList(ctx, models.List{CreatedBy: models.AdminUser}); !errors.Is(err, models.ErrInvalidInput) {
		t.Fatalf("unnamed CreateList() error = %v, want ErrInvalidInput", err)
	}

	if err := store.AddListItems(ctx, created.ID, []models.InstrumentID{"NSE:HDFCBANK", "NSE:SBIN"}); err != nil {
		t.Fatalf("AddListItems() error = %v", err)
	}
	if err := store.RemoveListItems(ctx, created.ID, []models.InstrumentID{"NSE:ICICIBANK"}); err != nil {
		t.Fatalf("RemoveListItems() error = %v", err)
	}
	got, err := store.GetList(ctx, created.ID)
	if err != nil {
		t.Fatalf("GetList() error = %v", err)
	}
	assertListIDs(t, got, "NSE:HDFCBANK", "NSE:SBIN")
	if !got.Items[0].CreatedAt.Equal(created.Items[0].CreatedAt) {
		t.Fatalf("re-added item created_at changed from %v to %v", created.Items[0].CreatedAt, got.Items[0].CreatedAt)
	}

	if err := store.AddListItems(ctx, "missing", []models.InstrumentID{"NSE:SBIN"}); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("AddListItems(missing) error = %v, want ErrNotFound", err)
	}
	if _, err := store.GetList(ctx, "missing"); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("GetList(missing) error = %v, want ErrNotFound", err)
	}
}

func TestListsRenameDeleteAndFilterByCreator(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	first := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "One"})
	second := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "Two"})
	other := mustCreateList(t, store, models.List{CreatedBy: "trader", Name: "One", Items: []models.ListItem{{InstrumentID: "NSE:TCS"}}})
	if first.Number != 1 || second.Number != 2 || other.Number != 1 {
		t.Fatalf("numbers = %d, %d, %d; want 1, 2, 1", first.Number, second.Number, other.Number)
	}

	if err := store.RenameList(ctx, second.ID, "One"); !errors.Is(err, models.ErrAlreadyExists) {
		t.Fatalf("RenameList(conflict) error = %v, want ErrAlreadyExists", err)
	}
	if err := store.RenameList(ctx, second.ID, "Renamed"); err != nil {
		t.Fatalf("RenameList() error = %v", err)
	}

	admin, err := store.GetLists(ctx, models.AdminUser)
	if err != nil {
		t.Fatalf("GetLists(ADMIN) error = %v", err)
	}
	if len(admin) != 2 || admin[0].Name != "One" || admin[1].Name != "Renamed" {
		t.Fatalf("admin lists = %#v", admin)
	}
	all, err := store.GetLists(ctx, "")
	if err != nil {
		t.Fatalf("GetLists(all) error = %v", err)
	}
	if len(all) != 3 || all[2].CreatedBy != "trader" {
		t.Fatalf("all lists = %#v", all)
	}
	assertListIDs(t, all[2], "NSE:TCS")

	if err := store.DeleteList(ctx, other.ID); err != nil {
		t.Fatalf("DeleteList() error = %v", err)
	}
	if err := store.DeleteList(ctx, other.ID); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("second DeleteList() error = %v, want ErrNotFound", err)
	}
	var orphanItems int
	if err := store.db.QueryRowContext(ctx, "SELECT count(*) FROM list_items WHERE list_id = ?", other.ID).Scan(&orphanItems); err != nil || orphanItems != 0 {
		t.Fatalf("orphan items = %d, err = %v", orphanItems, err)
	}
}

func TestReplaceAutoGeneratedListKeepsIdentityAndPrunesItems(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	index := models.List{
		CreatedBy: models.AdminUser,
		Name:      "NSE:NIFTY 50",
		IsIndex:   true,
		URL:       "https://www.niftyindices.com/indices/equity/broad-based-indices/nifty--50",
		Items:     []models.ListItem{{InstrumentID: "NSE:RELIANCE"}, {InstrumentID: "NSE:TCS"}},
	}
	first, err := store.ReplaceAutoGeneratedList(ctx, index)
	if err != nil {
		t.Fatalf("first ReplaceAutoGeneratedList() error = %v", err)
	}
	if !first.AutoGenerated || !first.IsIndex || first.URL != index.URL {
		t.Fatalf("first list = %#v", first)
	}

	index.Items = []models.ListItem{{InstrumentID: "NSE:TCS"}, {InstrumentID: "NSE:INFY"}}
	second, err := store.ReplaceAutoGeneratedList(ctx, index)
	if err != nil {
		t.Fatalf("second ReplaceAutoGeneratedList() error = %v", err)
	}
	if second.ID != first.ID || second.Number != first.Number {
		t.Fatalf("replace changed identity: %s/%d -> %s/%d", first.ID, first.Number, second.ID, second.Number)
	}
	got := map[models.InstrumentID]bool{}
	for _, id := range second.InstrumentIDs() {
		got[id] = true
	}
	if len(got) != 2 || !got["NSE:TCS"] || !got["NSE:INFY"] {
		t.Fatalf("replaced items = %v", second.InstrumentIDs())
	}
}

func TestListsPersistAndAreAddedToExistingCatalogs(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "instruments.duckdb")

	store, err := NewInstrumentsDuckDBRepository(ctx, path)
	if err != nil {
		t.Fatalf("NewInstrumentsDuckDBRepository() error = %v", err)
	}
	// Simulate a catalog created before lists existed.
	if _, err := store.db.ExecContext(ctx, "DROP TABLE list_items; DROP TABLE list_metadata"); err != nil {
		t.Fatalf("drop list tables: %v", err)
	}
	if err := store.Close(); err != nil {
		t.Fatalf("Close() error = %v", err)
	}

	store = openListStore(t, ctx, path)
	created := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "Watch", Items: []models.ListItem{{InstrumentID: "NSE:SBIN"}}})
	if err := store.Close(); err != nil {
		t.Fatalf("Close() error = %v", err)
	}

	store = openListStore(t, ctx, path)
	got, err := store.GetList(ctx, created.ID)
	if err != nil {
		t.Fatalf("GetList() after reopen error = %v", err)
	}
	assertListIDs(t, got, "NSE:SBIN")
}

func openListStore(t *testing.T, ctx context.Context, path string) *InstrumentsDuckDBRepository {
	t.Helper()
	store, err := NewInstrumentsDuckDBRepository(ctx, path)
	if err != nil {
		t.Fatalf("NewInstrumentsDuckDBRepository() error = %v", err)
	}
	t.Cleanup(func() { _ = store.Close() })
	return store
}

func mustCreateList(t *testing.T, store *InstrumentsDuckDBRepository, list models.List) models.List {
	t.Helper()
	created, err := store.CreateList(context.Background(), list)
	if err != nil {
		t.Fatalf("CreateList(%q) error = %v", list.Name, err)
	}
	return created
}

func assertListIDs(t *testing.T, list models.List, want ...models.InstrumentID) {
	t.Helper()
	if got := list.InstrumentIDs(); !reflect.DeepEqual(got, want) {
		t.Fatalf("list %q items = %v, want %v", list.Name, got, want)
	}
}
