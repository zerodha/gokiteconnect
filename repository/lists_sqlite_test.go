func TestListsCreateGetAndEditItems(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	created, err := store.CreateList(ctx, models.List{
		CreatedBy: models.AdminUser,
		Name:      " Banks ",
		Items:     []models.ListItem{{InstrumentID: "NSE:HDFCBANK"}, {InstrumentID: "NSE:ICICIBANK"}},
	})
	if err != nil {
		t.Fatalf("CreateList() error = %v", err)
	}
	if created.ID == "" || created.Number != 1 || created.Name != "Banks" || created.CreatedAt.IsZero() {
		t.Fatalf("created list = %#v", created)
	}
	assertListIDs(t, created, "NSE:HDFCBANK", "NSE:ICICIBANK")

	if _, err := store.CreateList(ctx, models.List{CreatedBy: models.AdminUser, Name: "Banks"}); !errors.Is(err, models.ErrAlreadyExists) {
		t.Fatalf("duplicate CreateList() error = %v, want ErrAlreadyExists", err)
	}
	if _, err := store.CreateList(ctx, models.List{CreatedBy: models.AdminUser}); !errors.Is(err, models.ErrInvalidInput) {
		t.Fatalf("unnamed CreateList() error = %v, want ErrInvalidInput", err)
	}

	if err := store.AddListItems(ctx, created.ID, []models.InstrumentID{"NSE:HDFCBANK", "NSE:SBIN"}); err != nil {
		t.Fatalf("AddListItems() error = %v", err)
	}
	if err := store.RemoveListItems(ctx, created.ID, []models.InstrumentID{"NSE:ICICIBANK"}); err != nil {
		t.Fatalf("RemoveListItems() error = %v", err)
	}
	got, err := store.GetList(ctx, created.ID)
	if err != nil {
		t.Fatalf("GetList() error = %v", err)
	}
	assertListIDs(t, got, "NSE:HDFCBANK", "NSE:SBIN")
	if !got.Items[0].CreatedAt.Equal(created.Items[0].CreatedAt) {
		t.Fatalf("re-added item created_at changed from %v to %v", created.Items[0].CreatedAt, got.Items[0].CreatedAt)
	}

	if err := store.AddListItems(ctx, "missing", []models.InstrumentID{"NSE:SBIN"}); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("AddListItems(missing) error = %v, want ErrNotFound", err)
	}
	if _, err := store.GetList(ctx, "missing"); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("GetList(missing) error = %v, want ErrNotFound", err)
	}
}

func TestListsRenameDeleteAndFilterByCreator(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	first := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "One"})
	second := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "Two"})
	other := mustCreateList(t, store, models.List{CreatedBy: "trader", Name: "One", Items: []models.ListItem{{InstrumentID: "NSE:TCS"}}})
	if first.Number != 1 || second.Number != 2 || other.Number != 1 {
		t.Fatalf("numbers = %d, %d, %d; want 1, 2, 1", first.Number, second.Number, other.Number)
	}

	if err := store.RenameList(ctx, second.ID, "One"); !errors.Is(err, models.ErrAlreadyExists) {
		t.Fatalf("RenameList(conflict) error = %v, want ErrAlreadyExists", err)
	}
	if err := store.RenameList(ctx, second.ID, "Renamed"); err != nil {
		t.Fatalf("RenameList() error = %v", err)
	}

	admin, err := store.GetLists(ctx, models.AdminUser)
	if err != nil {
		t.Fatalf("GetLists(ADMIN) error = %v", err)
	}
	if len(admin) != 2 || admin[0].Name != "One" || admin[1].Name != "Renamed" {
		t.Fatalf("admin lists = %#v", admin)
	}
	all, err := store.GetLists(ctx, "")
	if err != nil {
		t.Fatalf("GetLists(all) error = %v", err)
	}
	if len(all) != 3 || all[2].CreatedBy != "trader" {
		t.Fatalf("all lists = %#v", all)
	}
	assertListIDs(t, all[2], "NSE:TCS")

	if err := store.DeleteList(ctx, other.ID); err != nil {
		t.Fatalf("DeleteList() error = %v", err)
	}
	if err := store.DeleteList(ctx, other.ID); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("second DeleteList() error = %v, want ErrNotFound", err)
	}
	var orphanItems int
	if err := store.db.QueryRowContext(ctx, "SELECT count(*) FROM list_items WHERE list_id = ?", other.ID).Scan(&orphanItems); err != nil || orphanItems != 0 {
		t.Fatalf("orphan items = %d, err = %v", orphanItems, err)
	}
}

func TestReplaceAutoGeneratedListKeepsIdentityAndPrunesItems(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")

	index := models.List{
		CreatedBy: models.AdminUser,
		Name:      "NSE:NIFTY 50",
		IsIndex:   true,
		URL:       "https://www.niftyindices.com/indices/equity/broad-based-indices/nifty--50",
		Items:     []models.ListItem{{InstrumentID: "NSE:RELIANCE"}, {InstrumentID: "NSE:TCS"}},
	}
	first, err := store.ReplaceAutoGeneratedList(ctx, index)
	if err != nil {
		t.Fatalf("first ReplaceAutoGeneratedList() error = %v", err)
	}
	if !first.AutoGenerated || !first.IsIndex || first.URL != index.URL {
		t.Fatalf("first list = %#v", first)
	}

	index.Items = []models.ListItem{{InstrumentID: "NSE:TCS"}, {InstrumentID: "NSE:INFY"}}
	second, err := store.ReplaceAutoGeneratedList(ctx, index)
	if err != nil {
		t.Fatalf("second ReplaceAutoGeneratedList() error = %v", err)
	}
	if second.ID != first.ID || second.Number != first.Number {
		t.Fatalf("replace changed identity: %s/%d -> %s/%d", first.ID, first.Number, second.ID, second.Number)
	}
	got := map[models.InstrumentID]bool{}
	for _, id := range second.InstrumentIDs() {
		got[id] = true
	}
	if len(got) != 2 || !got["NSE:TCS"] || !got["NSE:INFY"] {
		t.Fatalf("replaced items = %v", second.InstrumentIDs())
	}
}

func TestSmartListsFollowTheirParent(t *testing.T) {
	ctx := context.Background()
	store := openListStore(t, ctx, ":memory:")
	parent, err := store.ReplaceAutoGeneratedList(ctx, models.List{CreatedBy: models.AdminUser, Name: "NIFTY 50", IsIndex: true, Items: []models.ListItem{
		{InstrumentID: "NSE:SBIN"}, {InstrumentID: "NSE:INFY"},
	}})
	if err != nil {
		t.Fatalf("ReplaceAutoGeneratedList() error = %v", err)
	}

	// A smart list keeps no items of its own: the ones given are ignored.
	smart := mustCreateList(t, store, models.List{CreatedBy: "AB1234", Name: "Nifty", ParentID: parent.ID, Items: []models.ListItem{{InstrumentID: "NSE:TCS"}}})
	if !smart.IsSmart() || smart.ParentID != parent.ID {
		t.Fatalf("smart list = %#v", smart)
	}
	assertListIDs(t, smart, "NSE:SBIN", "NSE:INFY")
	// One made from a smart list follows that list's parent.
	nested := mustCreateList(t, store, models.List{CreatedBy: "AB1234", Name: "Nifty again", ParentID: smart.ID})
	if nested.ParentID != parent.ID {
		t.Fatalf("nested smart list parent = %q, want %q", nested.ParentID, parent.ID)
	}
	if _, err := store.CreateList(ctx, models.List{CreatedBy: "AB1234", Name: "Orphan", ParentID: "missing"}); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("CreateList(missing parent) error = %v, want ErrNotFound", err)
	}

	// Refreshing the parent changes the smart list too.
	if _, err := store.ReplaceAutoGeneratedList(ctx, models.List{CreatedBy: models.AdminUser, Name: "NIFTY 50", IsIndex: true, Items: []models.ListItem{
		{InstrumentID: "NSE:INFY"}, {InstrumentID: "NSE:HDFCBANK"},
	}}); err != nil {
		t.Fatalf("ReplaceAutoGeneratedList() refresh error = %v", err)
	}
	got, err := store.GetList(ctx, smart.ID)
	if err != nil {
		t.Fatalf("GetList() error = %v", err)
	}
	assertListIDs(t, got, "NSE:INFY", "NSE:HDFCBANK")
	// GetLists reads the parent's items even when it filters the parent out.
	owned, err := store.GetLists(ctx, "AB1234")
	if err != nil {
		t.Fatalf("GetLists() error = %v", err)
	}
	if len(owned) != 2 {
		t.Fatalf("GetLists(AB1234) = %d lists, want 2", len(owned))
	}
	assertListIDs(t, owned[0], "NSE:INFY", "NSE:HDFCBANK")

	if err := store.AddListItems(ctx, smart.ID, []models.InstrumentID{"NSE:TCS"}); !errors.Is(err, models.ErrSmartList) {
		t.Fatalf("AddListItems(smart) error = %v, want ErrSmartList", err)
	}
	if err := store.RemoveListItems(ctx, smart.ID, []models.InstrumentID{"NSE:INFY"}); !errors.Is(err, models.ErrSmartList) {
		t.Fatalf("RemoveListItems(smart) error = %v, want ErrSmartList", err)
	}

	// Deleting the parent leaves the smart lists with its last items, as
	// their own.
	if err := store.DeleteList(ctx, parent.ID); err != nil {
		t.Fatalf("DeleteList(parent) error = %v", err)
	}
	for _, id := range []string{smart.ID, nested.ID} {
		kept, err := store.GetList(ctx, id)
		if err != nil {
			t.Fatalf("GetList() after the parent was deleted error = %v", err)
		}
		if kept.IsSmart() {
			t.Fatalf("%q still follows the deleted parent", kept.Name)
		}
		assertListIDs(t, kept, "NSE:INFY", "NSE:HDFCBANK")
	}
	if err := store.AddListItems(ctx, smart.ID, []models.InstrumentID{"NSE:TCS"}); err != nil {
		t.Fatalf("AddListItems() after detaching error = %v", err)
	}
}

func TestListsAddTheParentColumnToAnOlderDatabase(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "lists.sqlite3")
	db, err := sql.Open("sqlite3", path)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`
		CREATE TABLE list_metadata (
			list_id TEXT PRIMARY KEY, created_by TEXT NOT NULL, list_number INTEGER NOT NULL, name TEXT NOT NULL,
			is_index BOOLEAN NOT NULL DEFAULT FALSE, auto_generated BOOLEAN NOT NULL DEFAULT FALSE, url TEXT,
			created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL, UNIQUE (created_by, name));
		INSERT INTO list_metadata VALUES ('old', 'ADMIN', 1, 'Old', FALSE, FALSE, NULL, '2026-01-01 00:00:00', '2026-01-01 00:00:00');`,
	); err != nil {
		t.Fatal(err)
	}
	_ = db.Close()

	store := openListStore(t, ctx, path)
	old, err := store.GetList(ctx, "old")
	if err != nil || old.Name != "Old" || old.IsSmart() {
		t.Fatalf("GetList(old) = %#v, %v", old, err)
	}
	smart := mustCreateList(t, store, models.List{CreatedBy: "AB1234", Name: "Old", ParentID: "old"})
	if smart.ParentID != "old" {
		t.Fatalf("smart list = %#v", smart)
	}
}

func TestListsPersistAcrossReopen(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "lists.sqlite3")

	store := openListStore(t, ctx, path)
	created := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "Watch", Items: []models.ListItem{
		{InstrumentID: "NSE:SBIN"}, {InstrumentID: "NSE:AXISBANK"}, {InstrumentID: "NSE:ICICIBANK"},
	}})
	if err := store.Close(); err != nil {
		t.Fatalf("Close() error = %v", err)
	}

	// A second process can write while the first has it open.
	store = openListStore(t, ctx, path)
	other := openListStore(t, ctx, path)
	if err := other.AddListItems(ctx, created.ID, []models.InstrumentID{"NSE:HDFCBANK"}); err != nil {
		t.Fatalf("AddListItems() from a second handle error = %v", err)
	}
	got, err := store.GetList(ctx, created.ID)
	if err != nil {
		t.Fatalf("GetList() after reopen error = %v", err)
	}
	// Items keep the order they were added in, not ID order.
	assertListIDs(t, got, "NSE:SBIN", "NSE:AXISBANK", "NSE:ICICIBANK", "NSE:HDFCBANK")
}

func TestListsMigrateOnceFromTheDuckDBCatalog(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	instrumentsPath := filepath.Join(dir, "instruments.duckdb")
	legacy, err := sql.Open("duckdb", instrumentsPath)
	if err != nil {
		t.Fatal(err)
	}
	// The list tables as DuckDB catalogs held them.
	if _, err := legacy.ExecContext(ctx, `
		CREATE TABLE list_metadata (
			list_id TEXT PRIMARY KEY, created_by TEXT NOT NULL, list_number INTEGER NOT NULL, name TEXT NOT NULL,
			is_index BOOLEAN NOT NULL DEFAULT FALSE, auto_generated BOOLEAN NOT NULL DEFAULT FALSE, url TEXT,
			created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp, updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp);
		CREATE TABLE list_items (list_id TEXT NOT NULL, id TEXT NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp, PRIMARY KEY (list_id, id));
		INSERT INTO list_metadata (list_id, created_by, list_number, name, is_index, auto_generated, url)
			VALUES ('banks', 'ADMIN', 3, 'Banks', FALSE, FALSE, NULL),
			       ('nifty', 'ADMIN', 4, 'NSE:NIFTY 50', TRUE, TRUE, 'https://example.test/nifty');
		INSERT INTO list_items (list_id, id, created_at) VALUES
			('banks', 'NSE:SBIN', TIMESTAMPTZ '2026-01-01 10:00:00+00'),
			('banks', 'NSE:AXISBANK', TIMESTAMPTZ '2026-01-02 10:00:00+00'),
			('nifty', 'NSE:TCS', TIMESTAMPTZ '2026-01-01 10:00:00+00');
	`); err != nil {
		t.Fatalf("create legacy lists: %v", err)
	}
	if err := legacy.Close(); err != nil {
		t.Fatal(err)
	}

	listsPath := filepath.Join(dir, "lists.sqlite3")
	store, err := NewListsSQLiteRepository(ctx, listsPath, instrumentsPath)
	if err != nil {
		t.Fatalf("NewListsSQLiteRepository() error = %v", err)
	}
	lists, err := store.GetLists(ctx, models.AdminUser)
	if err != nil || len(lists) != 2 {
		t.Fatalf("migrated lists = %#v, %v", lists, err)
	}
	if lists[0].ID != "banks" || lists[0].Number != 3 || lists[1].URL != "https://example.test/nifty" || !lists[1].IsIndex || !lists[1].AutoGenerated {
		t.Fatalf("migrated lists = %#v", lists)
	}
	assertListIDs(t, lists[0], "NSE:SBIN", "NSE:AXISBANK")
	// New lists number after the migrated ones.
	if created := mustCreateList(t, store, models.List{CreatedBy: models.AdminUser, Name: "New"}); created.Number != 5 {
		t.Fatalf("new list number = %d, want 5", created.Number)
	}
	if err := store.DeleteList(ctx, "banks"); err != nil {
		t.Fatal(err)
	}
	if err := store.Close(); err != nil {
		t.Fatal(err)
	}

	// It runs once: a deleted list stays deleted.
	store = openListStoreFrom(t, ctx, listsPath, instrumentsPath)
	if _, err := store.GetList(ctx, "banks"); !errors.Is(err, models.ErrNotFound) {
		t.Fatalf("GetList(deleted) after reopen error = %v", err)
	}
}

func TestListsMigrateFromTheCopyKeptByAReplacedCatalog(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	instrumentsPath := filepath.Join(dir, "instruments.duckdb")
	// A catalog from before lists moved out, refreshed before any lists
	// store opened it.
	catalog, err := NewInstrumentsDuckDBRepository(ctx, instrumentsPath)
	if err != nil {
		t.Fatal(err)
	}
	if err := catalog.Close(); err != nil {
		t.Fatal(err)
	}
	writable, err := sql.Open("duckdb", instrumentsPath)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := writable.ExecContext(ctx, `
		CREATE TABLE list_metadata (list_id TEXT PRIMARY KEY, created_by TEXT NOT NULL, list_number INTEGER NOT NULL,
			name TEXT NOT NULL, is_index BOOLEAN NOT NULL DEFAULT FALSE, auto_generated BOOLEAN NOT NULL DEFAULT FALSE,
			url TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp, updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp);
		CREATE TABLE list_items (list_id TEXT NOT NULL, id TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp);
		INSERT INTO list_metadata (list_id, created_by, list_number, name) VALUES ('watch', 'ADMIN', 1, 'Watch');
		INSERT INTO list_items (list_id, id) VALUES ('watch', 'NSE:INFY');
		CHECKPOINT;
	`); err != nil {
		t.Fatal(err)
	}
	if err := writable.Close(); err != nil {
		t.Fatal(err)
	}
	catalog, err = NewInstrumentsDuckDBRepository(ctx, instrumentsPath)
	if err != nil {
		t.Fatal(err)
	}
	defer catalog.Close()
	if err := catalog.Replace(ctx, []models.Instrument{{ID: "NSE:INFY", Exchange: "NSE", TradingSymbol: "INFY", InstrumentToken: 408065, DisplayName: "INFY", SearchString: "INFY"}}, time.Now()); err != nil {
		t.Fatalf("Replace() error = %v", err)
	}

	store := openListStoreFrom(t, ctx, filepath.Join(dir, "lists.sqlite3"), instrumentsPath)
	got, err := store.GetList(ctx, "watch")
	if err != nil {
		t.Fatalf("GetList(migrated) error = %v", err)
	}
	assertListIDs(t, got, "NSE:INFY")
}

func openListStore(t *testing.T, ctx context.Context, path string) *ListsSQLiteRepository {
	t.Helper()
	return openListStoreFrom(t, ctx, path, "")
}

func openListStoreFrom(t *testing.T, ctx context.Context, path, legacyInstrumentsPath string) *ListsSQLiteRepository {
	t.Helper()
	store, err := NewListsSQLiteRepository(ctx, path, legacyInstrumentsPath)
	if err != nil {
		t.Fatalf("NewListsSQLiteRepository() error = %v", err)
	}
	t.Cleanup(func() { _ = store.Close() })
	return store
}

func mustCreateList(t *testing.T, store *ListsSQLiteRepository, list models.List) models.List {
	t.Helper()
	created, err := store.CreateList(context.Background(), list)
	if err != nil {
		t.Fatalf("CreateList(%q) error = %v", list.Name, err)
	}
	return created
}

func assertListIDs(t *testing.T, list models.List, want ...models.InstrumentID) {
	t.Helper()
	if got := list.InstrumentIDs(); !reflect.DeepEqual(got, want) {
		t.Fatalf("list %q items = %v, want %v", list.Name, got, want)
	}
}
