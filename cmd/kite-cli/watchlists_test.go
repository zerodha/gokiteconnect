// watchlistHarness opens the Watchlists tab over the SQLite list store,
// with an ADMIN list BANKS holding RELIANCE.
func watchlistHarness(t *testing.T) (*harness, *repository.ListsSQLiteRepository, models.List) {
	t.Helper()
	ctx := context.Background()
	lists, err := repository.NewListsSQLiteRepository(ctx, ":memory:", "")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = lists.Close() })
	banks, err := lists.ReplaceAutoGeneratedList(ctx, models.List{CreatedBy: models.AdminUser, Name: "BANKS", IsIndex: true, Items: []models.ListItem{{InstrumentID: "NSE:RELIANCE"}}})
	if err != nil {
		t.Fatal(err)
	}
	store, _ := niftyMarket()
	h := newHarness(t, explorerDeps(t, store, nil, lists, &fakePlacer{}))
	openExplorer(h)
	h.waitFor("the default watchlist", func() bool { return h.a.explorer.watching && h.idle() })
	return h, lists, banks
}

// shownIDs are the instruments in the table.
func shownIDs(e *explorerScreen) []models.InstrumentID {
	var ids []models.InstrumentID
	for _, instrument := range e.resultItems {
		ids = append(ids, instrument.ID)
	}
	return ids
}

func TestWatchlistsStartWithASmartDefaultSyncList(t *testing.T) {
	h, lists, _ := watchlistHarness(t)
	e := h.a.explorer
	ctx := context.Background()

	if !strings.Contains(h.screen(), "Watchlists") {
		t.Errorf("the tab is not called Watchlists:\n%s", h.screen())
	}
	// The user's first watchlist follows ADMIN's DEFAULT SYNC, built from
	// the catalog because there was none.
	own, err := lists.GetLists(ctx, "AB1234")
	if err != nil || len(own) != 1 {
		t.Fatalf("AB1234's lists = %+v, %v", own, err)
	}
	admin, err := lists.GetLists(ctx, models.AdminUser)
	if err != nil {
		t.Fatal(err)
	}
	parent := admin[slices.IndexFunc(admin, func(l models.List) bool { return l.Name == marketdata.DefaultSyncListName })]
	if own[0].Name != marketdata.DefaultSyncListName || own[0].ParentID != parent.ID {
		t.Fatalf("default watchlist = %+v, want smart over %s", own[0], parent.ID)
	}
	if got := shownIDs(e); !slices.Equal(got, []models.InstrumentID{"NSE:NIFTY 50", "NSE:RELIANCE"}) {
		t.Fatalf("shown = %v", got)
	}
	if screen := ansi.Strip(h.screen()); !strings.Contains(screen, "smart · follows DEFAULT SYNC · ‹ 1/1 ›") {
		t.Errorf("no watchlist header:\n%s", screen)
	}

	// Opening the tab again keeps the one watchlist.
	shown := e.watchGen
	h.press("esc", "w")
	h.waitFor("the watchlist again", func() bool { return e.watchGen > shown && e.watching && h.idle() })
	if own, _ := lists.GetLists(ctx, "AB1234"); len(own) != 1 {
		t.Fatalf("reopening made another watchlist: %+v", own)
	}

	// A smart watchlist can't be edited.
	h.press("d")
	if !strings.Contains(ansi.Strip(e.status), "is smart") {
		t.Errorf("X on a smart watchlist: status %q", ansi.Strip(e.status))
	}

	// A search replaces the watchlist; Esc brings it back.
	h.press("/")
	h.typeText("REL")
	h.waitFor("search results", func() bool { return !e.watching && !e.underlyings && len(e.resultItems) == 1 })
	h.press("esc", "esc")
	h.waitFor("the watchlist", func() bool { return e.watching && len(e.resultItems) == 2 })
}

func TestWatchlistsFromAdminListsSmartOrCloned(t *testing.T) {
	h, lists, banks := watchlistHarness(t)
	e := h.a.explorer
	ctx := context.Background()

	newFrom := func(parent, mode, name string) {
		t.Helper()
		h.press("n")
		picker, ok := h.a.overlay.(*menu)
		if !ok {
			t.Fatalf("N opened %T", h.a.overlay)
		}
		index := slices.IndexFunc(picker.items, func(item menuItem) bool { return strings.HasPrefix(ansi.Strip(item.label), parent) })
		if index < 0 {
			t.Fatalf("no %s in the picker", parent)
		}
		picker.cursor = index
		h.press("enter", mode)
		h.typeText(name)
		h.press("enter")
		// The name starts as the parent's.
		h.waitFor(parent+name, func() bool {
			list, ok := e.currentWatchlist()
			return ok && list.Name == parent+name && e.watching && h.idle()
		})
	}
	newFrom("BANKS", "s", " follows")
	newFrom("BANKS", "c", " copy")
	if got := shownIDs(e); !slices.Equal(got, []models.InstrumentID{"NSE:RELIANCE"}) {
		t.Fatalf("clone shows %v", got)
	}

	// Refreshing BANKS changes the smart watchlist, not the clone.
	if _, err := lists.ReplaceAutoGeneratedList(ctx, models.List{CreatedBy: models.AdminUser, Name: "BANKS", IsIndex: true, Items: []models.ListItem{
		{InstrumentID: "NSE:RELIANCE"}, {InstrumentID: "NSE:NIFTY 50"},
	}}); err != nil {
		t.Fatal(err)
	}
	shown := e.watchGen
	h.press("esc", "w")
	h.waitFor("the clone again", func() bool { return e.watchGen > shown && e.watching && h.idle() })
	if got := shownIDs(e); !slices.Equal(got, []models.InstrumentID{"NSE:RELIANCE"}) {
		t.Fatalf("clone after the refresh shows %v", got)
	}
	h.press("[")
	h.waitFor("the smart watchlist", func() bool {
		list, _ := e.currentWatchlist()
		return list.Name == "BANKS follows" && len(e.resultItems) == 2
	})
	if list, _ := e.currentWatchlist(); list.ParentID != banks.ID {
		t.Errorf("BANKS follows has parent %q, want %q", list.ParentID, banks.ID)
	}

	// ] wraps from the last watchlist to the first.
	h.press("]", "]")
	h.waitFor("the first watchlist", func() bool {
		list, _ := e.currentWatchlist()
		return list.Name == marketdata.DefaultSyncListName && e.watchIndex == 0
	})

	// The clone can be edited: D removes its selected instrument, and an
	// empty watchlist can be made, then deleted from the lists view.
	h.press("[")
	h.waitFor("the clone", func() bool {
		list, _ := e.currentWatchlist()
		return list.Name == "BANKS copy" && len(e.resultItems) == 1
	})
	h.press("d")
	h.waitFor("the removal", func() bool { return len(e.resultItems) == 0 && h.idle() })
	if !strings.Contains(h.screen(), "This watchlist is empty") {
		t.Errorf("no empty text:\n%s", h.screen())
	}

	h.press("n", "enter")
	h.typeText("Scratch")
	h.press("enter")
	h.waitFor("Scratch", func() bool { list, _ := e.currentWatchlist(); return list.Name == "Scratch" && h.idle() })
	h.press("l")
	h.waitFor("lists", func() bool { return e.mode == viewLists && h.idle() })
	e.listsGrid.selectWhere(func(r row) bool { return r.ref.(models.List).Name == "Scratch" })
	h.press("d", "left", "enter")
	h.waitFor("the deletion", func() bool { return len(e.watchlists) == 3 && h.idle() })
	h.press("esc")
	h.waitFor("the watchlist", func() bool { return e.mode == viewDashboard && e.watching })
	if own, _ := lists.GetLists(ctx, "AB1234"); len(own) != 3 {
		t.Fatalf("AB1234 has %d watchlists after the delete, want 3", len(own))
	}
}
