type catalog interface {
	Close() error
	Refresh(context.Context) error
	LastRefreshedAt(context.Context) (time.Time, error)
	Get(context.Context, models.InstrumentID) (models.Instrument, error)
	ListFO(context.Context, ...string) ([]models.Instrument, error)
	Search(context.Context, string, int) ([]models.Instrument, error)
	GetFutures(context.Context, models.FuturesFilter) ([]models.Instrument, error)
	GetOptions(context.Context, models.OptionsFilter) ([]models.Instrument, error)
}

// listStore persists instrument lists, in their own database opened and
// closed together with the catalog.
type listStore interface {
	GetLists(context.Context, string) ([]models.List, error)
	CreateList(context.Context, models.List) (models.List, error)
	ReplaceAutoGeneratedList(context.Context, models.List) (models.List, error)
	RenameList(context.Context, string, string) error
	DeleteList(context.Context, string) error
	AddListItems(context.Context, string, []models.InstrumentID) error
	RemoveListItems(context.Context, string, []models.InstrumentID) error
}

// indexSource discovers NSE indices and downloads their constituents.
type indexSource interface {
	ListIndices(context.Context) ([]nse.NSEIndexMetadata, error)
	GetIndex(context.Context, nse.NSEIndexMetadata) (models.List, error)
}

// catalogFactory opens the catalog and the list store opened with it. The
// list store may be nil when lists are unavailable.
type catalogFactory func(context.Context) (catalog, listStore, error)

type initialCatalog struct {
	catalog       catalog
	lists         listStore
	underlyings   []models.Instrument
	lastRefreshed time.Time
}

func loadInitialCatalog(ctx context.Context, factory catalogFactory) (initialCatalog, error) {
	catalog, lists, err := factory(ctx)
	if err != nil {
		return initialCatalog{}, err
	}
	lastRefreshed, err := catalog.LastRefreshedAt(ctx)
	if err != nil {
		_ = catalog.Close()
		return initialCatalog{}, err
	}
	underlyings, err := catalog.ListFO(ctx)
	if err != nil {
		_ = catalog.Close()
		return initialCatalog{}, err
	}
	return initialCatalog{catalog: catalog, lists: lists, underlyings: underlyings, lastRefreshed: lastRefreshed}, nil
}

