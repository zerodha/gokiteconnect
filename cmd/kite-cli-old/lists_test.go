func TestListsViewCreatesListsAndDownloadsNSEIndices(t *testing.T) {
	store := &fakeCatalog{underlyings: []models.Instrument{
		{ID: "NSE:RELIANCE", TradingSymbol: "RELIANCE", DisplayName: "RELIANCE", FuturesCount: 1},
		{ID: "NSE:TCS", TradingSymbol: "TCS", DisplayName: "TCS", FuturesCount: 1},
		{ID: "NSE:NIFTY 50", TradingSymbol: "NIFTY 50", DisplayName: "NIFTY 50", Segment: "INDICES", OptionsCount: 1},
	}}
	lists := &fakeListStore{}
	indices := &fakeIndexSource{
		metadata: []nse.NSEIndexMetadata{{TradingSymbol: "nifty 50", IndexName: "Nifty 50", ListName: "NSE:NIFTY 50", IndexPageURL: "https://example.test/nifty-50"}},
		constituents: map[string][]models.InstrumentID{
			"https://example.test/nifty-50": {"NSE:RELIANCE", "NSE:TCS"},
		},
	}
	ui := newInstrumentApp(context.Background(), ":memory:", func(context.Context) (catalog, listStore, error) {
		return store, lists, nil
	}, indices)
	screen := tcell.NewSimulationScreen("UTF-8")
	screen.SetSize(140, 40)
	ui.application.SetScreen(screen)

	done := make(chan error, 1)
	go func() { done <- ui.run() }()
	defer func() {
		ui.stop()
		<-done
	}()
	waitForApp(t, ui, func() bool { return ui.catalog == store && !ui.busy })

	pressRune(ui, 'l')
	waitForApp(t, ui, func() bool { return ui.mode == viewLists && !ui.busy })

	pressRune(ui, 'm')
	waitForApp(t, ui, func() bool { return ui.overlay == masterPage })
	// The first row is the F&O list built from the catalog.
	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyEnter, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return ui.overlay == masterPage && len(ui.listData) == 1 })
	fo := lists.byName("FO_LIST")
	if fo.CreatedBy != models.AdminUser || fo.IsIndex || !fo.AutoGenerated {
		t.Fatalf("F&O list = %#v", fo)
	}
	if got := fo.InstrumentIDs(); len(got) != 3 || got[2] != "NSE:NIFTY 50" {
		t.Fatalf("F&O list = %v, want RELIANCE, TCS and NIFTY 50", got)
	}

	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyDown, 0, tcell.ModNone))
	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyEnter, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return ui.overlay == masterPage && len(ui.listData) == 2 })

	index := lists.byName("NSE:NIFTY 50")
	if index.CreatedBy != models.AdminUser || !index.IsIndex || !index.AutoGenerated || index.URL != "https://example.test/nifty-50" || len(index.Items) != 2 {
		t.Fatalf("downloaded index list = %#v", index)
	}

	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyEscape, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return ui.overlay == "" && ui.mode == viewLists })

	pressRune(ui, 'n')
	waitForApp(t, ui, func() bool { return ui.overlay == listFormPage })
	typeText(ui, "Swing")
	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyEnter, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return len(ui.listData) == 3 && !ui.busy })

	swing := lists.byName("Swing")
	if swing.CreatedBy != models.AdminUser || swing.AutoGenerated {
		t.Fatalf("created list = %#v", swing)
	}
	waitForApp(t, ui, func() bool {
		selected, ok := ui.selectedList()
		return ok && selected.ID == swing.ID
	})

	pressRune(ui, 'a')
	waitForApp(t, ui, func() bool { return ui.overlay == listFormPage })
	typeText(ui, "nse:tcs")
	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyEnter, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return !ui.busy && len(lists.byName("Swing").Items) == 1 })
	if got := lists.byName("Swing").Items[0].InstrumentID; got != "NSE:TCS" {
		t.Fatalf("added instrument = %q, want NSE:TCS", got)
	}

	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyTab, 0, tcell.ModNone))
	waitForApp(t, ui, func() bool { return ui.listItemsFocused })
	pressRune(ui, 'd')
	waitForApp(t, ui, func() bool { return !ui.busy && len(lists.byName("Swing").Items) == 0 })

	pressRune(ui, 'q')
	waitForApp(t, ui, func() bool { return ui.mode == viewDashboard })
}

func pressRune(ui *instrumentApp, r rune) {
	ui.application.QueueEvent(tcell.NewEventKey(tcell.KeyRune, r, tcell.ModNone))
}

func typeText(ui *instrumentApp, text string) {
	for _, r := range text {
		pressRune(ui, r)
	}
}

type fakeListStore struct {
	mu    sync.Mutex
	lists []models.List
}

func (f *fakeListStore) byName(name string) models.List {
	f.mu.Lock()
	defer f.mu.Unlock()
	for _, list := range f.lists {
		if list.Name == name {
			return list
		}
	}
	return models.List{}
}

func (f *fakeListStore) GetLists(context.Context, string) ([]models.List, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	return append([]models.List(nil), f.lists...), nil
}

func (f *fakeListStore) CreateList(_ context.Context, list models.List) (models.List, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	list.ID = fmt.Sprintf("list-%d", len(f.lists)+1)
	list.Number = len(f.lists) + 1
	list.UpdatedAt = time.Now()
	f.lists = append(f.lists, list)
	return list, nil
}

func (f *fakeListStore) ReplaceAutoGeneratedList(ctx context.Context, list models.List) (models.List, error) {
	f.mu.Lock()
	for i, existing := range f.lists {
		if existing.Name == list.Name && existing.CreatedBy == list.CreatedBy {
			list.ID, list.Number, list.AutoGenerated = existing.ID, existing.Number, true
			f.lists[i] = list
			f.mu.Unlock()
			return list, nil
		}
	}
	f.mu.Unlock()
	list.AutoGenerated = true
	return f.CreateList(ctx, list)
}

func (f *fakeListStore) RenameList(_ context.Context, id, name string) error {
	return f.update(id, func(list *models.List) { list.Name = name })
}

func (f *fakeListStore) DeleteList(_ context.Context, id string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	for i, list := range f.lists {
		if list.ID == id {
			f.lists = append(f.lists[:i], f.lists[i+1:]...)
			return nil
		}
	}
	return models.ErrNotFound
}

func (f *fakeListStore) AddListItems(_ context.Context, id string, ids []models.InstrumentID) error {
	return f.update(id, func(list *models.List) {
		for _, instrumentID := range ids {
			list.Items = append(list.Items, models.ListItem{InstrumentID: instrumentID, CreatedAt: time.Now()})
		}
	})
}

func (f *fakeListStore) RemoveListItems(_ context.Context, id string, ids []models.InstrumentID) error {
	return f.update(id, func(list *models.List) {
		kept := list.Items[:0]
		for _, item := range list.Items {
			remove := false
			for _, instrumentID := range ids {
				remove = remove || item.InstrumentID == instrumentID
			}
			if !remove {
				kept = append(kept, item)
			}
		}
		list.Items = kept
	})
}

func (f *fakeListStore) update(id string, change func(*models.List)) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	for i := range f.lists {
		if f.lists[i].ID == id {
			list := f.lists[i]
			list.Items = append([]models.ListItem(nil), list.Items...)
			change(&list)
			f.lists[i] = list
			return nil
		}
	}
	return models.ErrNotFound
}

type fakeIndexSource struct {
	metadata     []nse.NSEIndexMetadata
	constituents map[string][]models.InstrumentID
}

func (f *fakeIndexSource) ListIndices(context.Context) ([]nse.NSEIndexMetadata, error) {
	return f.metadata, nil
}

func (f *fakeIndexSource) GetIndex(_ context.Context, metadata nse.NSEIndexMetadata) (models.List, error) {
	ids, ok := f.constituents[metadata.IndexPageURL]
	if !ok {
		return models.List{}, models.ErrNotFound
	}
	list := models.List{Name: metadata.ListName, IsIndex: true, AutoGenerated: true, URL: metadata.IndexPageURL}
	for _, id := range ids {
		list.Items = append(list.Items, models.ListItem{InstrumentID: id})
	}
	return list, nil
}
