package marketdata

import (
	"context"
	"path/filepath"
	"slices"
	"testing"

	"github.com/devshoe/gokiteconnect/models"
	"github.com/devshoe/gokiteconnect/repository"
)

// fakeCatalog has a few indices and NSE and BSE F&O underlyings.
type fakeCatalog struct {
	indices []models.InstrumentID
	fo      []models.Instrument
}

func (f fakeCatalog) Get(_ context.Context, id models.InstrumentID) (models.Instrument, error) {
	if slices.Contains(f.indices, id) {
		return models.Instrument{ID: id}, nil
	}
	return models.Instrument{}, models.ErrNotFound
}

func (f fakeCatalog) ListFO(_ context.Context, exchanges ...string) ([]models.Instrument, error) {
	var out []models.Instrument
	for _, instrument := range f.fo {
		if slices.Contains(exchanges, instrument.Exchange) {
			out = append(out, instrument)
		}
	}
	return out, nil
}

func TestDefaultSyncListIsIndicesThenNSEUnderlyings(t *testing.T) {
	catalog := fakeCatalog{
		indices: []models.InstrumentID{"NSE:NIFTY 50", "NSE:NIFTY BANK", "BSE:SENSEX"},
		fo: []models.Instrument{
			{ID: "NSE:NIFTY 50", Exchange: "NSE"},
			{ID: "NSE:RELIANCE", Exchange: "NSE"},
			{ID: "NSE:TCS", Exchange: "NSE"},
			{ID: "BSE:BANKEX", Exchange: "BSE"},
		},
	}
	list, err := DefaultSyncList(context.Background(), catalog)
	if err != nil {
		t.Fatal(err)
	}
	want := []models.InstrumentID{"NSE:NIFTY 50", "NSE:NIFTY BANK", "BSE:SENSEX", "NSE:RELIANCE", "NSE:TCS"}
	if got := list.InstrumentIDs(); !slices.Equal(got, want) {
		t.Fatalf("items = %v, want %v", got, want)
	}
	if list.Name != DefaultSyncListName || list.CreatedBy != models.AdminUser || !list.AutoGenerated {
		t.Errorf("list = %+v", list)
	}
}

func TestRebuildDefaultSyncListReplacesTheStoredList(t *testing.T) {
	ctx := context.Background()
	store, err := repository.NewListsSQLiteRepository(ctx, filepath.Join(t.TempDir(), "lists.sqlite3"), "")
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	catalog := fakeCatalog{indices: []models.InstrumentID{"BSE:SENSEX"}, fo: []models.Instrument{{ID: "NSE:TCS", Exchange: "NSE"}}}
	first, err := RebuildDefaultSyncList(ctx, catalog, store)
	if err != nil {
		t.Fatal(err)
	}
	catalog.fo = []models.Instrument{{ID: "NSE:INFY", Exchange: "NSE"}}
	second, err := RebuildDefaultSyncList(ctx, catalog, store)
	if err != nil {
		t.Fatal(err)
	}
	if first.ID != second.ID {
		t.Errorf("rebuild made a new list: %s then %s", first.ID, second.ID)
	}
	got := second.InstrumentIDs()
	slices.Sort(got)
	if want := []models.InstrumentID{"BSE:SENSEX", "NSE:INFY"}; !slices.Equal(got, want) {
		t.Fatalf("items = %v, want %v", got, want)
	}
}
